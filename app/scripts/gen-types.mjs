// Generates app/src/generated/<Name>.ts from every docs/json-schema/<Name>.json.
// Deterministic: sorted, fixed banner, no timestamp. Run: npm run gen:types
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.resolve(here, "../../docs/json-schema");
const outDir = path.resolve(here, "../src/generated");

const schemas = (await readdir(schemaDir)).filter((f) => f.endsWith(".json")).sort();
await mkdir(outDir, { recursive: true });

const wanted = new Set();
for (const file of schemas) {
  const name = path.basename(file, ".json");
  const ts = await compileFromFile(path.join(schemaDir, file), {
    bannerComment: `// Generated by npm run gen:types from docs/json-schema/${file}. Do not edit.`,
    cwd: schemaDir,
  });
  await writeFile(path.join(outDir, `${name}.ts`), ts);
  wanted.add(`${name}.ts`);
}

for (const file of await readdir(outDir)) {
  if (file.endsWith(".ts") && !wanted.has(file)) {
    await rm(path.join(outDir, file));
  }
}
console.log(`wrote ${wanted.size} types to src/generated`);
